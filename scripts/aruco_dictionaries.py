"""Writes crates/mapping/src/aruco_dictionaries.rs from OpenCV's predefined ArUco dictionaries.

Run with any python that has cv2 (e.g. dimos's .venv): python scripts/aruco_dictionaries.py > crates/mapping/src/aruco_dictionaries.rs
Each code is the marker's bits row by row from the top-left cell (the first cell is the most significant bit), 1 = white,
in the marker's upright orientation (rotation 0). DICT_NxN_50/100/250 are the first 50/100/250 of DICT_NxN_1000.
"""
import cv2
import numpy as np

aruco = cv2.aruco
SOURCES = [("DICT_4X4_1000", "ARUCO_4X4"), ("DICT_5X5_1000", "ARUCO_5X5"), ("DICT_6X6_1000", "ARUCO_6X6"), ("DICT_7X7_1000", "ARUCO_7X7"), ("DICT_ARUCO_ORIGINAL", "ARUCO_ORIGINAL"), ("DICT_ARUCO_MIP_36h12", "ARUCO_MIP_36H12")]
NAMES = [f"DICT_{s}X{s}_{n}" for s in (4, 5, 6, 7) for n in (50, 100, 250, 1000)] + ["DICT_ARUCO_ORIGINAL", "DICT_ARUCO_MIP_36h12"]


def codes(name):
    dictionary = aruco.getPredefinedDictionary(getattr(aruco, name))
    size = dictionary.markerSize
    out = []
    for index in range(dictionary.bytesList.shape[0]):
        bits = aruco.Dictionary.getBitsFromByteList(dictionary.bytesList[index : index + 1], size).reshape(-1)
        code = 0
        for bit in bits:
            code = (code << 1) | int(bit)
        out.append(code)
    return size, out


print(f"//! OpenCV {cv2.__version__}'s predefined ArUco dictionaries, generated by scripts/aruco_dictionaries.py: don't edit.")
print("//! A code is the marker's bits row by row from the top-left cell (first cell = most significant bit), 1 = white.")
print()
for source, constant in SOURCES:
    size, values = codes(source)
    print(f"pub static {constant}: [u64; {len(values)}] = [")
    for start in range(0, len(values), 8):
        print("    " + ", ".join(f"0x{v:0{(size * size + 3) // 4}x}" for v in values[start : start + 8]) + ",")
    print("];")
    print()
print("/// (OpenCV name, marker size in cells, codes (the first `count`), count, OpenCV's maxCorrectionBits for it)")
print("pub static DICTIONARIES: &[(&str, usize, &[u64], usize, usize)] = &[")
for name in NAMES:
    dictionary = aruco.getPredefinedDictionary(getattr(aruco, name))
    size = dictionary.markerSize
    count = dictionary.bytesList.shape[0]
    constant = next(c for s, c in SOURCES if aruco.getPredefinedDictionary(getattr(aruco, s)).markerSize == size and np.array_equal(aruco.getPredefinedDictionary(getattr(aruco, s)).bytesList[:count], dictionary.bytesList))
    print(f'    ("{name}", {size}, &{constant}, {count}, {dictionary.maxCorrectionBits}),')
print("];")
